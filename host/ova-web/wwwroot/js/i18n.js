let current = "en";

export function locale() {
  return current;
}

export function detectLocale() {
  const n = (navigator.language || "en").toLowerCase();
  return n.startsWith("zh") ? "zh-CN" : "en";
}

export function setLocale(next) {
  current = next === "zh-CN" ? "zh-CN" : "en";
  document.documentElement.lang = current === "zh-CN" ? "zh-CN" : "en";
}

export function t(key, vars) {
  const table = catalogs[current] || catalogs.en;
  let s = table[key] || catalogs.en[key] || key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] == null ? "" : String(vars[k])));
  return s;
}

export function applyI18n() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-label]").forEach((el) => {
    const label = t(el.dataset.i18nLabel);
    el.setAttribute("label", label);
    if ("label" in el) el.label = label;
  });
  document.querySelectorAll("[data-i18n-support]").forEach((el) => {
    const s = t(el.dataset.i18nSupport);
    el.setAttribute("supporting-text", s);
    if ("supportingText" in el) el.supportingText = s;
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.dataset.i18nPlaceholder));
  });
  const fail = document.getElementById("boot-fail");
  if (fail) fail.textContent = t("boot.fail");
}
